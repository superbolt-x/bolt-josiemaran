with
dtc_sales_vs_spend__today as (
-- The calendar date in the business timezone, from the dbt_project.yml var
    -- time_zone. getdate returns UTC, which is already "tomorrow" for the last
    -- four evening hours of an Eastern day.
    select convert_timezone('US/Eastern', getdate())::date as today_local
),

dtc_sales_vs_spend__shopify_daily as (
select
        date,
        sum(first_order_gross_sales)    as new_customer_gross_sales,
        sum(repeat_order_gross_sales)   as returning_customer_gross_sales,
        sum(gross_sales)                as gross_sales,
        sum(new_customers)              as new_customers
    from reporting.josiemaran_shopify_sales_by_segment
    where date_granularity = 'day'
      and date <= (select today_local from dtc_sales_vs_spend__today) - 1
    group by 1
),

dtc_sales_vs_spend__spend_rows as (
select
        lower(channel)      as platform,
        campaign_id,
        segment,
        date,
        sum(spend)          as spend
    from reporting.josiemaran_blended_performance
    where date_granularity = 'day'
      and channel in ('Meta', 'Google', 'TikTok')
      and date >= (select min(date) from dtc_sales_vs_spend__shopify_daily)
    group by 1, 2, 3, 4
),

dtc_sales_vs_spend__freshness as (
-- Last day each platform has synced, capped at yesterday, taken over EVERY
    -- campaign on the platform so a paused campaign cannot make it look stale.
    select
        platform,
        least(max(date), (select today_local from dtc_sales_vs_spend__today) - 1) as actuals_through
    from dtc_sales_vs_spend__spend_rows
    group by 1
),

dtc_sales_vs_spend__typed_spend as (
-- Only budget lines that have a spend_type. Days past the dtc_sales_vs_spend__freshness limit of
    -- their platform are dropped here, so they come out NULL below rather than 0.
    -- No apostrophes in comments in this file: the standalone compiler reads one as
    -- the start of a string and skips renaming CTE references until the next one.
    -- The mapping is
    -- INLINED, not a shared CTE, for the Redshift planner reason noted in
    -- blended_performance.sql.
    select
        s.date,
        s.platform,
        m.spend_type,
        sum(s.spend)        as spend
    from dtc_sales_vs_spend__spend_rows s
    join ( (select 'meta'::varchar(16)  as platform,
               '120251956330760613'::varchar(32) as campaign_id,
               ''::varchar(64) as segment_match,
               'dtc'::varchar(32) as business_unit,
               'prospecting_advplus'::varchar(64) as campaign_key,
               'prospecting'::varchar(16) as spend_type
        union all select 'meta', '120214146763940613', '', 'dtc', 'temp_retargeting', 'mixed'
        union all select 'meta', '120252630357450613', '', 'dtc', 'lead_gen', 'prospecting'
        union all select 'google', '21703833786', '', 'dtc', 'us_branded_pmax', 'brand'
        union all select 'google', '21704002557', '', 'dtc', 'us_branded_search', 'brand'
        union all select 'google', '21703908630', '', 'dtc', 'ca_branded_search', 'brand'
        union all select 'google', '24209915936', '', 'dtc', 'nb_pmax', 'nonbrand'
        union all select 'tiktok', '1876696959444129', '', 'dtc', 'gmv_max', ''
        union all select 'meta', '120250319355050303', '', 'sephora_us', 'us_traffic', ''
        union all select 'meta', '120219945963310303', '', 'sephora_us', 'us_collab', ''
        union all select 'meta', '120250632750520303', 'Sephora US Collab', 'sephora_us', 'new_us_collab', ''
        union all select 'tiktok', '1874691217255666', '', 'sephora_us', 'us_traffic', ''
        union all select 'tiktok', '1836369380956178', '', 'sephora_us', 'us_traffic', ''
        union all select 'meta', '120250328578570303', '', 'sephora_ca', 'ca_traffic', ''
        union all select 'meta', '120239209497810303', '', 'sephora_ca', 'ca_collab', ''
        union all select 'meta', '120250632750520303', 'Sephora CA Collab', 'sephora_ca', 'new_ca_collab', ''
        union all select 'tiktok', '1874694608225890', '', 'sephora_ca', 'ca_traffic', ''
        union all select 'tiktok', '1836386473412625', '', 'sephora_ca', 'ca_traffic', ''
        union all select 'meta', '120234201732920613', '', 'sephora_kohls', 'kohls_us_traffic', '') ) m
        on  m.platform    = s.platform
        and m.campaign_id = s.campaign_id
        and (m.segment_match = '' or m.segment_match = s.segment)
    join dtc_sales_vs_spend__freshness f
        on  f.platform = s.platform
    where m.spend_type <> ''
      and s.date <= f.actuals_through
    group by 1, 2, 3
),

dtc_sales_vs_spend__spend_by_day as (
select
        date,
        sum(case when platform = 'meta'   then spend end)      as spend_meta,
        sum(case when platform = 'google' then spend end)      as spend_google,
        sum(case when platform = 'tiktok' then spend end)      as spend_tiktok,
        sum(case when spend_type = 'prospecting' then spend end) as spend_prospecting,
        sum(case when spend_type = 'mixed'       then spend end) as spend_mixed,
        sum(case when spend_type = 'brand'       then spend end) as spend_brand,
        sum(case when spend_type = 'nonbrand'    then spend end) as spend_nonbrand
    from dtc_sales_vs_spend__typed_spend
    group by 1
),

dtc_sales_vs_spend as (
select
    h.date,
    date_trunc('month', h.date)::date   as month_start,
    h.new_customer_gross_sales,
    h.returning_customer_gross_sales,
    h.gross_sales,
    h.new_customers,
    p.spend_meta,
    p.spend_google,
    p.spend_tiktok,
    p.spend_prospecting,
    p.spend_mixed,
    p.spend_brand,
    p.spend_nonbrand
from dtc_sales_vs_spend__shopify_daily h
left join dtc_sales_vs_spend__spend_by_day p
    on  p.date = h.date
)

select
    date,
    month_start,
    new_customer_gross_sales,
    returning_customer_gross_sales,
    gross_sales,
    new_customers,
    spend_meta,
    spend_google,
    spend_tiktok,
    spend_prospecting,
    spend_mixed,
    spend_brand,
    spend_nonbrand
from dtc_sales_vs_spend
where month_start >=
        date_trunc('month', dateadd(month, -1, convert_timezone('US/Eastern', getdate())))::date
order by date
