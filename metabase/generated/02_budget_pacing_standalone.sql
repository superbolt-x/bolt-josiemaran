with
budget_pacing__today as (
-- The calendar date in the business timezone, from the dbt_project.yml
    -- var time_zone. getdate returns UTC, which is already "tomorrow" for the
    -- last four evening hours of an Eastern day.
    select convert_timezone('US/Eastern', getdate())::date as today_local
),

budget_pacing__budget_rows as (
select
        date                as date,
        business_unit,
        platform,
        campaign_key,
        budget              as forecast_budget
    from gsheet_raw.josie_maran_budget_forecast
),

budget_pacing__spend_daily as (
select
        lower(channel)      as platform,
        campaign_id,
        segment,
        date,
        sum(spend)          as spend
    from reporting.josiemaran_blended_performance
    where date_granularity = 'day'
      and channel in ('Meta', 'Google', 'TikTok')
      and date >= (select min(date) from budget_pacing__budget_rows)
    group by 1, 2, 3, 4
),

budget_pacing__freshness as (
-- Last day each platform has synced, capped at yesterday. Taken over EVERY
    -- campaign on the platform, not just the mapped ones, so a paused campaign
    -- with no rows cannot make the platform look stale.
    select
        platform,
        least(max(date), (select today_local from budget_pacing__today) - 1) as actuals_through
    from budget_pacing__spend_daily
    group by 1
),

budget_pacing__mapped_spend as (
select
        m.business_unit,
        m.platform,
        m.campaign_key,
        s.date,
        sum(s.spend)        as actual_spend
    from budget_pacing__spend_daily s
    join ( (select 'meta'::varchar(16)  as platform,
               '120251956330760613'::varchar(32) as campaign_id,
               ''::varchar(64) as segment_match,
               'dtc'::varchar(32) as business_unit,
               'prospecting_advplus'::varchar(64) as campaign_key
        union all select 'meta', '120214146763940613', '', 'dtc', 'temp_retargeting'
        union all select 'meta', '120252630357450613', '', 'dtc', 'lead_gen'
        union all select 'google', '21703833786', '', 'dtc', 'us_branded_pmax'
        union all select 'google', '21704002557', '', 'dtc', 'us_branded_search'
        union all select 'google', '21703908630', '', 'dtc', 'ca_branded_search'
        union all select 'google', '24209915936', '', 'dtc', 'nb_pmax'
        union all select 'tiktok', '1876696959444129', '', 'dtc', 'gmv_max'
        union all select 'meta', '120250319355050303', '', 'sephora_us', 'us_traffic'
        union all select 'meta', '120219945963310303', '', 'sephora_us', 'us_collab'
        union all select 'meta', '120250632750520303', 'Sephora US Collab', 'sephora_us', 'new_us_collab'
        union all select 'tiktok', '1874691217255666', '', 'sephora_us', 'us_traffic'
        union all select 'tiktok', '1836369380956178', '', 'sephora_us', 'us_traffic'
        union all select 'meta', '120250328578570303', '', 'sephora_ca', 'ca_traffic'
        union all select 'meta', '120239209497810303', '', 'sephora_ca', 'ca_collab'
        union all select 'meta', '120250632750520303', 'Sephora CA Collab', 'sephora_ca', 'new_ca_collab'
        union all select 'tiktok', '1874694608225890', '', 'sephora_ca', 'ca_traffic'
        union all select 'tiktok', '1836386473412625', '', 'sephora_ca', 'ca_traffic'
        union all select 'meta', '120234201732920613', '', 'sephora_kohls', 'kohls_us_traffic') ) m
        on  m.platform    = s.platform
        and m.campaign_id = s.campaign_id
        and (m.segment_match = '' or m.segment_match = s.segment)
    group by 1, 2, 3, 4
),

budget_pacing__joined as (
-- Full outer, so both of these survive: a budgeted line with no spend yet
    -- (a future day, or a line that has not launched) and spend on a day that
    -- has no budget row (an unbudgeted campaign).
    select
        coalesce(b.date,          s.date)           as date,
        coalesce(b.business_unit, s.business_unit)  as business_unit,
        coalesce(b.platform,      s.platform)       as platform,
        coalesce(b.campaign_key,  s.campaign_key)   as campaign_key,
        b.forecast_budget,
        s.actual_spend
    from budget_pacing__budget_rows b
    full outer join budget_pacing__mapped_spend s
        on  s.date          = b.date
        and s.business_unit = b.business_unit
        and s.platform      = b.platform
        and s.campaign_key  = b.campaign_key
),

budget_pacing as (
select
    j.date,
    date_trunc('month', j.date)::date                                         as month_start,
    j.business_unit,
    j.platform,
    j.campaign_key,
    k.legend_label,
    k.stack_order,
    k.forecast_color,
    k.actual_color,
    j.forecast_budget,
    case when j.date <= f.actuals_through then coalesce(j.actual_spend, 0) end as actual_spend,
    case when j.date <= f.actuals_through then 1 else 0 end                    as is_actual,
    f.actuals_through
from budget_pacing__joined j
left join ( (select 'dtc'::varchar(32) as business_unit,
               'meta'::varchar(16) as platform,
               'prospecting_advplus'::varchar(64) as campaign_key,
