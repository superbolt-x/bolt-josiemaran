        union all select 'sephora_kohls', 'meta', 'kohls_us_traffic', 'Meta Traffic', 1, '#A4C2F4', '#999999') ) k
    on  k.business_unit = j.business_unit
    and k.platform      = j.platform
    and k.campaign_key  = j.campaign_key
left join budget_pacing__freshness f
    on  f.platform = j.platform
)

select
    date,
    month_start,
    business_unit,
    platform,
    campaign_key,
    legend_label,
    stack_order,
    forecast_color,
    actual_color,
    forecast_budget,
    actual_spend,
    is_actual
from budget_pacing
where month_start between
        date_trunc('month', dateadd(month, -1, convert_timezone('US/Eastern', getdate())))::date
    and date_trunc('month', dateadd(month,  1, convert_timezone('US/Eastern', getdate())))::date
order by month_start, business_unit, stack_order, date
