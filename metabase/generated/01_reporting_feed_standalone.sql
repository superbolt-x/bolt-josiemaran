facebook_catalog_segment_performance__actions as (
select
        campaign_id,
        date,
        action_type,
        sum(value)       as cnt,
        sum(_7_d_click)  as cnt_7d_click,
        sum(_1_d_view)   as cnt_1d_view
    from facebook_raw.campaigns_insights_catalog_segment_actions
    group by 1, 2, 3
